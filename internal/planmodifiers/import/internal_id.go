package planmodifiers

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework/attr"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/types"

	"github.com/infobloxopen/terraform-provider-infoblox/internal/flex"
)

func (m *associateInternalId) PlanModifyMap(ctx context.Context, req planmodifier.MapRequest, resp *planmodifier.MapResponse) {
	associateInternalId, diags := req.Private.GetKey(ctx, "associate_internal_id")
	resp.Diagnostics.Append(diags...)
	// Normal Update flow
	// Assumption : terraform_internal_id will never change externally (As it is generated by the provider).
	if associateInternalId == nil && !req.State.Raw.IsNull() {
		resp.PlanValue = extAttrsAllPlan(ctx, req, resp)
		return
	}
	// Regular import and first create should not suppress the diff.
	resp.PlanValue = types.MapUnknown(types.StringType)
}

// extAttrsAllPlan drops inherited EAs now overridden in ext_attrs, since apply moves them out of ext_attrs_all.
func extAttrsAllPlan(ctx context.Context, req planmodifier.MapRequest, resp *planmodifier.MapResponse) types.Map {
	if req.StateValue.IsNull() || req.StateValue.IsUnknown() {
		return req.StateValue
	}

	var extAttrs types.Map
	resp.Diagnostics.Append(req.Plan.GetAttribute(ctx, req.Path.ParentPath().AtName("ext_attrs"), &extAttrs)...)
	if resp.Diagnostics.HasError() {
		return req.StateValue
	}
	if extAttrs.IsUnknown() {
		return types.MapUnknown(types.StringType)
	}

	userEAs := extAttrs.Elements()
	stateEAs := req.StateValue.Elements()
	kept := make(map[string]attr.Value, len(stateEAs))
	for k, v := range stateEAs {
		// Internal ID always stays in ext_attrs_all.
		if _, overridden := userEAs[k]; overridden && k != flex.TerraformInternalID {
			continue
		}
		kept[k] = v
	}

	if len(kept) == len(stateEAs) {
		return req.StateValue
	}
	if len(kept) == 0 {
		return types.MapNull(types.StringType)
	}
	result, d := types.MapValue(types.StringType, kept)
	resp.Diagnostics.Append(d...)
	return result
}

type associateInternalId struct{}

func (m *associateInternalId) Description(ctx context.Context) string {
	return "Marks the entire map attribute as unknown during plan when associate_internal_id private key is set."
}

func (m *associateInternalId) MarkdownDescription(ctx context.Context) string {
	return "Marks the entire map attribute as unknown during plan when associate_internal_id private key is set."
}

func AssociateInternalId() planmodifier.Map {
	return &associateInternalId{}
}
